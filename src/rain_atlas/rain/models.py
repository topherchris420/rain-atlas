"""Candidate surrogate models and the Bayesian discrimination book.

The scientific problem used by the unified system: two coupled oscillators
whose phase coherence as a function of coupling strength is generated by one
of two candidate models. The twin (see
:mod:`rain_atlas.simulation.twin`) hides which model is true; the research
agents hold both candidate forms and design experiments to discriminate.

Both forms are *known surrogate models* -- the same approach the existing
ATLAS physical-scientist prototype uses. Nothing here invents physics: the
candidates are declared explicitly, and the decision rule is preregistered
before any observation.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

LINEAR = "linear"
DAMPED = "damped"
CANDIDATES = (LINEAR, DAMPED)


def predict_coherence(model: str, coupling: float) -> float:
    """Mean phase-coherence predicted by *model* at *coupling*."""

    if model == LINEAR:
        return 1.0 - math.exp(-3.0 * coupling)
    if model == DAMPED:
        amplitude = 0.5 + 0.5 * coupling
        effective = coupling * (1.0 - 0.45 * amplitude * amplitude)
        return 1.0 - math.exp(-3.0 * effective)
    raise ValueError(f"unknown candidate model {model!r}")


@dataclass(frozen=True)
class GridCondition:
    """One experimental condition on the twin."""

    coupling: float


@dataclass(frozen=True)
class Observation:
    """One observation: a condition and its measured coherence."""

    coupling: float
    coherence: float
    replicates: int

    def to_dict(self) -> dict:
        return {
            "coupling": self.coupling,
            "coherence": self.coherence,
            "replicates": self.replicates,
        }


class CandidateModels:
    """The preregistered decision book over two candidate surrogate models."""

    def __init__(
        self,
        *,
        observation_sigma: float = 0.06,
        replicates: int = 8,
        decision_log_bayes: float = 5.0,
    ) -> None:
        self.observation_sigma = observation_sigma
        self.replicates = replicates
        self.decision_log_bayes = decision_log_bayes

    @property
    def effective_sigma(self) -> float:
        """Standard error of the ensemble mean."""

        return self.observation_sigma / math.sqrt(self.replicates)

    def log_likelihood(self, model: str, observations: list[Observation]) -> float:
        if not observations:
            return 0.0
        sigma = self.effective_sigma
        total = 0.0
        for obs in observations:
            predicted = predict_coherence(model, obs.coupling)
            residual = (obs.coherence - predicted) / sigma
            total += -0.5 * residual * residual
        return total

    def log_bayes_factor(self, observations: list[Observation]) -> float:
        """Positive favors linear; negative favors damped."""

        return self.log_likelihood(LINEAR, observations) - self.log_likelihood(DAMPED, observations)

    def posterior_probability(self, model: str, observations: list[Observation]) -> float:
        lbf = self.log_bayes_factor(observations)
        if model == LINEAR:
            return 1.0 / (1.0 + math.exp(-lbf))
        return 1.0 / (1.0 + math.exp(lbf))

    def preferred_model(self, observations: list[Observation]) -> str:
        return LINEAR if self.log_bayes_factor(observations) >= 0 else DAMPED

    def decided(self, observations: list[Observation]) -> bool:
        return abs(self.log_bayes_factor(observations)) >= self.decision_log_bayes

    def disagreement(self, coupling: float) -> float:
        """Predicted separation between candidates at *coupling*."""

        return abs(predict_coherence(LINEAR, coupling) - predict_coherence(DAMPED, coupling))
