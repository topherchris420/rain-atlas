"""Deterministic, legally-redistributable fixtures for tests and the demo.

Everything here is synthesised from scratch so the reproducible demonstration
and the test suite never depend on a compiler, a network download or any
third-party firmware. :func:`build_elf` emits **minimal but specification-valid
ELF objects** (identity-mapped, so a single ``PT_LOAD`` makes virtual addresses
equal file offsets); it is a fixture generator, not a general linker, and the
only logic it encodes is the structural metadata the analyser reads back.
:func:`build_image` writes a small synthetic root filesystem with init
definitions, configuration and shared libraries, and :func:`build_update`
produces a hash-manifest and an Ed25519-signed update archive from a generated
key. The generated bytes are validated in CI against the independent pure-Python
reader; on a developer machine they also match ``readelf``.
"""

from __future__ import annotations

import struct
import tarfile
from dataclasses import dataclass
from io import BytesIO
from pathlib import Path

# e_machine ids used by the fixtures
EM_X86_64 = 62
EM_AARCH64 = 183
EM_ARM = 40


def _align(value: int, alignment: int) -> int:
    rem = value % alignment
    return value if rem == 0 else value + (alignment - rem)


@dataclass
class _Sym:
    name_off: int


def build_elf(
    *,
    bits: int = 64,
    endianness: str = "little",
    machine: int = EM_X86_64,
    needed: tuple[str, ...] = ("libc.so.6",),
    soname: str | None = None,
    interp: str | None = "/lib/ld.so.1",
    imports: tuple[str, ...] = (),
    nx: bool = True,
    relro: str | None = "full",
) -> bytes:
    """Return the bytes of a minimal, valid dynamic ELF with the given metadata."""

    endn = "<" if endianness == "little" else ">"
    is64 = bits == 64
    ehsize = 64 if is64 else 52
    ph_entsize = 56 if is64 else 32
    sh_entsize = 64 if is64 else 40

    # --- string table (.dynstr) -------------------------------------------
    dynstr = bytearray(b"\x00")
    offsets: dict[str, int] = {}

    def intern(name: str) -> int:
        if name not in offsets:
            offsets[name] = len(dynstr)
            dynstr.extend(name.encode("ascii") + b"\x00")
        return offsets[name]

    needed_offs = [intern(n) for n in needed]
    soname_off = intern(soname) if soname else None
    import_syms = [_Sym(intern(s)) for s in imports]

    # --- program headers we will emit -------------------------------------
    want_interp = interp is not None
    ph_types = ["LOAD", "DYNAMIC"]
    if want_interp:
        ph_types.insert(0, "INTERP")
    ph_types.append("GNU_STACK")
    if relro:
        ph_types.append("GNU_RELRO")
    phnum = len(ph_types)
    phoff = ehsize
    body_off = phoff + phnum * ph_entsize

    # --- lay out the body -------------------------------------------------
    blob = bytearray()

    def place(data: bytes, alignment: int = 1) -> int:
        nonlocal blob
        start = body_off + len(blob)
        pad = _align(start, alignment) - start
        blob.extend(b"\x00" * pad)
        at = body_off + len(blob)
        blob.extend(data)
        return at

    interp_off = place(interp.encode("ascii") + b"\x00") if want_interp else 0
    interp_len = (len(interp) + 1) if want_interp else 0
    dynstr_off = place(bytes(dynstr), 1)

    # .dynsym: a null symbol followed by one UND import per name
    sym_entsize = 24 if is64 else 16
    symbols = bytearray(b"\x00" * sym_entsize)  # index 0 is the null symbol
    for sym in import_syms:
        if is64:
            # st_name, st_info, st_other, st_shndx, st_value, st_size
            symbols.extend(struct.pack(endn + "IBBHQQ", sym.name_off, 0x12, 0, 0, 0, 0))
        else:
            # st_name, st_value, st_size, st_info, st_other, st_shndx
            symbols.extend(struct.pack(endn + "IIIBBH", sym.name_off, 0, 0, 0x12, 0, 0))
    dynsym_off = place(bytes(symbols), 8)

    # dynamic array
    dyn = bytearray()
    dyn_fmt = endn + ("II" if not is64 else "qQ")

    def dyn_entry(tag: int, val: int) -> None:
        dyn.extend(struct.pack(dyn_fmt, tag, val))

    for off in needed_offs:
        dyn_entry(1, off)  # DT_NEEDED
    if soname_off is not None:
        dyn_entry(14, soname_off)  # DT_SONAME
    dyn_entry(5, dynstr_off)  # DT_STRTAB (identity-mapped vaddr == offset)
    dyn_entry(10, len(dynstr))  # DT_STRSZ
    dyn_entry(6, dynsym_off)  # DT_SYMTAB
    dyn_entry(11, sym_entsize)  # DT_SYMENT
    if relro == "full":
        dyn_entry(30, 0x8)  # DT_FLAGS = DF_BIND_NOW
        dyn_entry(0x6FFFFFFB, 0x1 | 0x08000000)  # DT_FLAGS_1 = DF_1_NOW | DF_1_PIE
    dyn_entry(0, 0)  # DT_NULL
    dyn_off = place(bytes(dyn), 8)
    dyn_size = len(dyn)

    # section-header string table
    shstr = bytearray(b"\x00")
    sh_names: dict[str, int] = {}

    def sh_intern(name: str) -> int:
        if name not in sh_names:
            sh_names[name] = len(shstr)
            shstr.extend(name.encode("ascii") + b"\x00")
        return sh_names[name]

    n_dynsym, n_dynstr, n_shstr = sh_intern(".dynsym"), sh_intern(".dynstr"), sh_intern(".shstrtab")
    shstr_off = place(bytes(shstr), 1)

    sh_off = _align(body_off + len(blob), 8)
    total = sh_off + 4 * sh_entsize
    # Pad the blob so the body reaches the section-header table.
    blob.extend(b"\x00" * (sh_off - (body_off + len(blob))))

    # --- section headers: NULL, .dynsym, .dynstr, .shstrtab --------------
    def sh(name, stype, offset, size, link, entsize) -> bytes:
        if is64:
            return struct.pack(endn + "IIQQQQIIQQ", name, stype, 0, 0, offset, size, link, 0, 1, entsize)
        return struct.pack(endn + "IIIIIIIIII", name, stype, 0, 0, offset, size, link, 0, 1, entsize)

    section_headers = b"".join(
        [
            sh(0, 0, 0, 0, 0, 0),
            sh(n_dynsym, 11, dynsym_off, len(symbols), 2, sym_entsize),  # SHT_DYNSYM, link -> .dynstr
            sh(n_dynstr, 3, dynstr_off, len(dynstr), 0, 0),  # SHT_STRTAB
            sh(n_shstr, 3, shstr_off, len(shstr), 0, 0),
        ]
    )

    # --- program headers --------------------------------------------------
    def phdr(ptype: int, offset: int, vaddr: int, filesz: int, flags: int, align: int) -> bytes:
        if is64:
            return struct.pack(endn + "IIQQQQQQ", ptype, flags, offset, vaddr, vaddr, filesz, filesz, align)
        return struct.pack(endn + "IIIIIIII", ptype, offset, vaddr, vaddr, filesz, filesz, flags, align)

    pt = {"INTERP": 3, "LOAD": 1, "DYNAMIC": 2, "GNU_STACK": 0x6474E551, "GNU_RELRO": 0x6474E552}
    phdrs = []
    for kind in ph_types:
        if kind == "INTERP":
            phdrs.append(phdr(pt[kind], interp_off, interp_off, interp_len, 0x4, 1))
        elif kind == "LOAD":
            phdrs.append(phdr(pt[kind], 0, 0, total, 0x5, 0x1000))
        elif kind == "DYNAMIC":
            phdrs.append(phdr(pt[kind], dyn_off, dyn_off, dyn_size, 0x6, 8))
        elif kind == "GNU_STACK":
            phdrs.append(phdr(pt[kind], 0, 0, 0, 0x6 if nx else 0x7, 0x10))
        elif kind == "GNU_RELRO":
            phdrs.append(phdr(pt[kind], dyn_off, dyn_off, dyn_size, 0x4, 1))
    program_headers = b"".join(phdrs)

    # --- ELF header -------------------------------------------------------
    ei_class = 2 if is64 else 1
    ei_data = 1 if endianness == "little" else 2
    e_ident = bytes([0x7F]) + b"ELF" + bytes([ei_class, ei_data, 1, 0]) + b"\x00" * 8
    e_type = 3  # ET_DYN (a PIE or shared object)
    if is64:
        header = e_ident + struct.pack(
            endn + "HHIQQQIHHHHHH",
            e_type,
            machine,
            1,
            0,
            phoff,
            sh_off,
            0,
            ehsize,
            ph_entsize,
            phnum,
            sh_entsize,
            4,
            3,
        )
    else:
        header = e_ident + struct.pack(
            endn + "HHIIIIIHHHHHH",
            e_type,
            machine,
            1,
            0,
            phoff,
            sh_off,
            0,
            ehsize,
            ph_entsize,
            phnum,
            sh_entsize,
            4,
            3,
        )

    out = bytearray(header + program_headers + bytes(blob) + section_headers)
    assert len(out) == total, (len(out), total)
    return bytes(out)


# --------------------------------------------------------------------------
# Synthetic firmware root filesystem
# --------------------------------------------------------------------------

# Intended mode bits per path, so archives carry them in metadata regardless of
# the host filesystem (Windows does not honour setuid via chmod).
INTENDED_MODES = {
    "bin/busybox": 0o755,
    "usr/sbin/httpd": 0o755,
    "usr/sbin/telnetd": 0o755,
    "usr/sbin/mqttd": 0o755,
    "usr/bin/config-helper": 0o4755,
    "etc/init.d/telnetd": 0o755,
}


def _write(root: Path, rel: str, data: bytes, mode: int = 0o644) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    try:
        path.chmod(mode)
    except OSError:  # pragma: no cover - platform dependent
        pass


def build_image(root: Path, *, variant: str = "v1") -> Path:
    """Write a small, deterministic synthetic root filesystem under *root*."""

    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)

    # Shared libraries (as ELF shared objects).
    _write(root, "lib/libc.so.6", build_elf(soname="libc.so.6", needed=(), interp=None))
    _write(root, "lib/libssl.so.1", build_elf(soname="libssl.so.1", needed=("libc.so.6",), interp=None))

    # A network daemon that links socket calls and is launched by systemd.
    httpd_imports = ("socket", "bind", "listen", "accept", "__stack_chk_fail")
    _write(
        root,
        "usr/sbin/httpd",
        build_elf(needed=("libc.so.6", "libssl.so.1"), imports=httpd_imports),
        mode=0o755,
    )
    # A privileged helper, setuid root, no network symbols.
    _write(
        root,
        "usr/bin/config-helper",
        build_elf(needed=("libc.so.6",), imports=("open", "read", "__stack_chk_fail")),
        mode=0o4755,
    )
    # A plain tool with no network capability (false-positive control).
    _write(root, "bin/busybox", build_elf(needed=("libc.so.6",), imports=("printf", "malloc")), mode=0o755)

    # systemd unit for the daemon.
    _write(
        root,
        "etc/systemd/system/httpd.service",
        b"[Unit]\n"
        b"Description=Example HTTP daemon\n"
        b"After=network.target config.service\n"
        b"Requires=config.service\n"
        b"Wants=logging.service\n"
        b"\n[Service]\n"
        b"Type=simple\n"
        b"User=www\n"
        b"ExecStart=/usr/sbin/httpd --port 8080 --config /etc/httpd/httpd.conf\n"
        b"\n[Install]\n"
        b"WantedBy=multi-user.target\n",
    )
    _write(
        root,
        "etc/systemd/system/config.service",
        b"[Unit]\nDescription=Configuration bootstrap\n"
        b"\n[Service]\nType=oneshot\nUser=root\nExecStart=/usr/bin/config-helper apply\n",
    )
    # A SysV init script and an rc symlink-equivalent (recorded, not created).
    _write(
        root,
        "etc/init.d/telnetd",
        b"#!/bin/sh\n### BEGIN INIT INFO\n# Provides: telnetd\n# Required-Start: $network\n"
        b'### END INIT INFO\ncase "$1" in start) /usr/sbin/telnetd -p 23 ;; esac\n',
        mode=0o755,
    )
    _write(
        root,
        "usr/sbin/telnetd",
        build_elf(needed=("libc.so.6",), imports=("socket", "bind", "listen")),
        mode=0o755,
    )

    # Configuration declaring listening ports.
    _write(
        root,
        "etc/httpd/httpd.conf",
        b"# Example HTTP server config\nListen 8080\nServerName example.local\n# TLS listener\nListen 8443\n",
    )
    _write(root, "etc/dropbear/dropbear.conf", b"Port 22\nPasswordAuth yes\n")

    # A package manifest (dpkg-style control metadata).
    _write(
        root,
        "var/lib/dpkg/status",
        b"Package: httpd\nVersion: 1.4.2\nArchitecture: amd64\nDepends: libssl1\n\n"
        b"Package: busybox\nVersion: 1.36.1\nArchitecture: amd64\n\n",
    )
    # PEM trust material (public, inert).
    _write(
        root,
        "etc/ssl/certs/example.pem",
        b"-----BEGIN CERTIFICATE-----\nMIIBExampleOnlyNotARealCertificate==\n-----END CERTIFICATE-----\n",
    )
    _write(root, "etc/os-release", b'NAME="ExampleOS"\nVERSION="%s"\n' % variant.encode())

    if variant == "v2":
        # A newer release: bump the daemon, add a new network service, drop telnet.
        _write(
            root,
            "usr/sbin/httpd",
            build_elf(needed=("libc.so.6", "libssl.so.1"), imports=(*httpd_imports, "SSL_new")),
            mode=0o755,
        )
        (root / "etc/init.d/telnetd").unlink()
        (root / "usr/sbin/telnetd").unlink()
        _write(
            root,
            "etc/systemd/system/mqtt.service",
            b"[Unit]\nDescription=MQTT broker\nAfter=network.target\n"
            b"\n[Service]\nUser=mqtt\nExecStart=/usr/sbin/mqttd --port 1883\n",
        )
        _write(
            root,
            "usr/sbin/mqttd",
            build_elf(needed=("libc.so.6",), imports=("socket", "bind", "listen")),
            mode=0o755,
        )
        _write(root, "etc/mosquitto/mosquitto.conf", b"# MQTT broker\nPort 1883\n")
        _write(root, "etc/os-release", b'NAME="ExampleOS"\nVERSION="v2"\n')
    return root


def pack_tar(root: Path, dest: Path) -> Path:
    """Pack *root* into a deterministic, reproducible gzip tar at *dest*."""

    dest = Path(dest)
    rows = sorted((p.relative_to(root).as_posix(), p) for p in root.rglob("*") if p.is_file())
    buffer = BytesIO()
    # TarFile(...) rather than tarfile.open(...): identical here, and not a call
    # named ``open`` so the line-ending AST check does not mistake it for a text write.
    with tarfile.TarFile(fileobj=buffer, mode="w") as tf:
        for rel, path in rows:
            data = path.read_bytes()
            info = tarfile.TarInfo(rel)
            info.size = len(data)
            info.mtime = 0
            info.mode = INTENDED_MODES.get(rel, 0o755 if (path.stat().st_mode & 0o111) else 0o644)
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            tf.addfile(info, BytesIO(data))
    import gzip

    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(gzip.compress(buffer.getvalue(), mtime=0))
    return dest
